def vocab_md(v: dict) -> str:
    lines = [
        "---",
        f"category: vocabulary",
        f"title: {v['title']}",
        f"content_hash: gen_{v['slug']}",
        f"difficulty: {v['difficulty']}",
        f"tags: {v['tags']}",
        "language: ko",
        "source_url: generated",
        "---",
        f"# {v['title']}",
        "",
        f"**品詞：** {v['pos']}",
        "",
        f"**意思：** {v['meaning']}",
        "",
        "## 발음（發音）",
        "",
        v["pronunciation"],
        "",
    ]
    if v["confusable"]:
        lines += ["## 易混淆詞", "", v["confusable"], ""]
    lines += ["## 例句", ""]
    for ex in v["examples"]:
        lines.append(f"- {ex}")
    lines.append("")
    return "\n".join(lines)


def topik_md(t: dict) -> str:
    lines = [
        "---",
        f"category: topik_questions",
        f"title: {t['title']}",
        f"content_hash: gen_{t['slug']}",
        f"difficulty: {t['difficulty']}",
        f"tags: {t['tags']}",
        "language: ko",
        "source_url: generated",
        "---",
        f"# {t['title']}",
        "",
    ]
    for q in t["questions"]:
        lines += [
            f"## 題目 {q['n']}",
            "",
            q["prompt"],
            "",
        ]
        for opt in q["options"]:
            lines.append(opt)
        lines += [
            "",
            f"**正確答案：{q['answer']}**",
            "",
            "**解析：**",
            q["explanation"],
            "",
            "---",
            "",
        ]
    return "\n".join(lines)


